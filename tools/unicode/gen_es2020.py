#!/usr/bin/env python3
"""Writes src/es2020_gen.jl, the Unicode property names and values of the tables of ECMAScript 2020, from es2020.rs of
the corvus-regex-ecma262 Rust crate, so every engine's 2020 grammar knows the same names.

    python3 tools/unicode/gen_es2020.py <path to es2020.rs> [output] [--check]

With --check, the output is compared with the file in place and nothing is written: the exit status is 1 when they
differ.
"""
import os
import re
import sys

OUT = "src/es2020_gen.jl"
PER_LINE = 100


def names(rs, rust_fn):
    """The names a Rust `matches!` of the function lists."""
    m = re.search(r"fn " + rust_fn + r"\(name: &str\) -> bool \{\s*matches!\(\s*name,(.*?)\)\s*\}", rs, re.S)
    if m is None:
        raise SystemExit(f"es2020.rs has no {rust_fn}: the generator needs updating for the crate's file")
    found = re.findall(r'"([^"]*)"', m.group(1))
    if not found:
        raise SystemExit(f"es2020.rs lists no names in {rust_fn}")
    return found


def set_of(const, doc, values):
    """A constant set of the names, as many to a line as fit in 120 columns."""
    out = [f"# {doc}", f"const {const} = Set{{String}}(["]
    line = "   "
    for v in values:
        piece = f' "{v}",'
        if len(line) + len(piece) > 120:
            out.append(line)
            line = "   "
        line += piece
    out.append(line)
    out.append("])")
    return "\n".join(out)


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv
    rs = open(args[0], encoding="utf-8").read()
    output = args[1] if len(args) > 1 else OUT
    tables = [("ES2020_NON_BINARY", "The non-binary properties.", names(rs, "non_binary")),
              ("ES2020_BINARY", "The binary properties.", names(rs, "binary")),
              ("ES2020_CATEGORY", "The General_Category values.", names(rs, "category")),
              ("ES2020_SCRIPT", "The Script values.", names(rs, "script"))]
    parts = [
        "# Code generated by tools/unicode/gen_es2020.py from es2020.rs of the corvus-regex-ecma262 Rust crate. DO NOT EDIT.",
        "",
        "# The Unicode property names and values of the tables of ECMAScript 2020 (ECMA-262, 11th edition), the only ones",
        "# its grammar knows whatever the version of Unicode: tc39/ecma262 at the tag es2020, every name and alias of each.",
        "",
    ]
    for const, doc, values in tables:
        parts += [set_of(const, doc, values), ""]
    parts += [
        '"""',
        "Whether the expression between the braces of \\\\p{...} names a property, and a value of it, of the tables of",
        "ECMAScript 2020: a name and a value joined by =, or the lone name of a General_Category value or of a binary",
        "property.",
        '"""',
        "function es2020_has_property(expr::AbstractString)",
        "    eq = findfirst('=', expr)",
        "    if eq === nothing",
        "        return expr in ES2020_CATEGORY || expr in ES2020_BINARY",
        "    end",
        "    name, value = expr[1:eq-1], expr[eq+1:end]",
        "    if name in (\"General_Category\", \"gc\")",
        "        return value in ES2020_CATEGORY",
        "    end",
        "    return name in ES2020_NON_BINARY && value in ES2020_SCRIPT",
        "end",
    ]
    text = "\n".join(parts) + "\n"
    count = sum(len(v) for _, _, v in tables)
    if check:
        current = open(output, encoding="utf-8").read() if os.path.exists(output) else ""
        if current != text:
            print(f"{output} is not what {args[0]} generates; run tools/unicode/gen_es2020.py", file=sys.stderr)
            sys.exit(1)
        print(f"{output} is current ({count} names)")
        return
    with open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {output}: {count} names")


if __name__ == "__main__":
    main()
